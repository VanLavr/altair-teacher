"""Интерфейсы зависимостей service; здесь нет конкретной БД или HTTP-клиента."""
from typing import Protocol
from ..models.domain import ReservationData, Reservation


class RepositoryPort(Protocol):
    async def get(self, record_id: int) -> Reservation | None: ...
    async def list(self, limit: int, offset: int) -> list[Reservation]: ...
    # Protocol описывает нужные операции. Service не знает о PostgreSQL.
    async def create(self, data: ReservationData, status: str) -> Reservation: ...


class DownstreamsPort(Protocol):
    async def pay(self, order_id: int, amount: int) -> None: ...
    async def finish_order(self, order_id: int, status: str) -> None: ...
