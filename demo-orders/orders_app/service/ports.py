"""Интерфейсы зависимостей service; здесь нет конкретной БД или HTTP-клиента."""
from typing import Protocol
from ..models.domain import OrderData, Order


class RepositoryPort(Protocol):
    async def get(self, record_id: int) -> Order | None: ...
    async def list(self, limit: int, offset: int) -> list[Order]: ...
    # Protocol описывает нужные операции. Service не знает о PostgreSQL.
    async def create(self, data: OrderData, status: str) -> Order: ...
    async def set_status(self, record_id: int, status: str) -> Order | None: ...


class DownstreamsPort(Protocol):
    async def reserve(self, order_id: int, product_name: str, quantity: int, amount: int) -> None: ...
