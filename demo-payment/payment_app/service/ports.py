"""Интерфейсы зависимостей service; здесь нет конкретной БД или HTTP-клиента."""
from typing import Protocol
from ..models.domain import PaymentData, Payment


class RepositoryPort(Protocol):
    async def get(self, record_id: int) -> Payment | None: ...
    async def list(self, limit: int, offset: int) -> list[Payment]: ...
    # Protocol описывает нужные операции. Service не знает о PostgreSQL.
    async def create(self, data: PaymentData, status: str) -> Payment: ...


class DownstreamsPort(Protocol):
    async def deliver(self, order_id: int, address: str) -> None: ...
    async def finish_order(self, order_id: int, status: str) -> None: ...
