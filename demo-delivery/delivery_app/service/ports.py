"""Интерфейсы зависимостей service; здесь нет конкретной БД или HTTP-клиента."""
from typing import Protocol
from ..models.domain import DeliveryData, Delivery


class RepositoryPort(Protocol):
    async def get(self, record_id: int) -> Delivery | None: ...
    async def list(self, limit: int, offset: int) -> list[Delivery]: ...
    # Protocol описывает нужные операции. Service не знает о PostgreSQL.
    async def create(self, data: DeliveryData, status: str) -> Delivery: ...


class DownstreamsPort(Protocol):
    async def notify(self, order_id: int, message: str) -> None: ...
    async def finish_order(self, order_id: int, status: str) -> None: ...
